from math import pow
import numpy as np

from palantir.prediction_tools import Planet, Star, StellarWind

import logging
log = logging.getLogger('palantir.prediction_tools.emission')

# ============================================================= #
# -------------------------- Emission ------------------------- #
# ============================================================= #


class Emission:
    def __init__(
        self,
        name: str,
        planetary_magnetic_field: dict,
        pow_emission: dict,
        flux_received: dict,
        free_free_spi : dict,
        free_free_ms : dict,
        fcmax_star: dict,
        fp_planet : dict,
        fp_star : dict,
    ):
        """Creates an Emission object.

        :param name:
            Name of the target.
        :type name:
            str

        :param planetary_magnetic_field:
            Dictionnary with the relevant Planet and MagneticMoment objects to compute the magnetic field generated by the dynamo at the planet. Should have the fields "magnetic_moment" and "planet".
        :type planetary_magnetic_field:
            dict

        :param pow_emission:
            Dictionnary with the relevant Planet, Star, MagneticMoment, StellarWind and sw_jupiter objects to compute both the kinetic and magnetic power of the emission.
        :type pow_emission:
            dict
        :param pow_received:
            Dictionnary with the relevant Star object to compute both kinetic and magnetic power of the emission at Earth.
        :type pow_received:
            dict
        :param fcmax_star:
            Maximum frequency of the emission at the star, in Hz.
        :type fmax_star:
            float
        """

        self.name = name
        self.mag_field_planet = planetary_magnetic_field
        self.freq_p_planet = fp_planet
        self.freq_p_star = fp_star
        self._freq_c_max_planet = None
        self.freq_c_max_star = fcmax_star
        self.test_escaping_spi = fcmax_star
        self.pow_emission_kinetic = pow_emission
        self.pow_emission_magnetic = pow_emission
        self.pow_emission_spi = pow_emission
        self._flux_kinetic_au = None
        self._flux_magnetic_au = None
        self._flux_spi_au = None
        self.flux_received_kinetic = flux_received
        self.flux_received_magnetic = flux_received
        self.flux_received_spi = flux_received
        self.tau_free_free_spi = free_free_spi
        self.tau_free_free_ms = free_free_ms


    def __str__(self):
        return("Maximum frequency emission at the planet : fcp_max = {} MHz \n".format(self.freq_c_max_planet * 1e-6)
            + "Maximum frequency emission at the star : fc*_max = {} MHz \n".format(self.freq_c_max_star * 1e-6)
            + "Plasma frequency emission at the planet : fpp = {} MHz \n".format(self.freq_p_planet * 1e-6)
            + "Plasma frequency emission at the star : fp* = {} MHz \n".format(self.freq_p_star * 1e-6)
            + "Maximum magnetic field at the planet : Bpla = {} T\n".format(self.mag_field_planet)
            + "Kinetic power of the emission at the system : Pkin_em = {} .10^14 W\n".format(self.pow_emission_kinetic / 1e14)
            + "Magnetic power of the emission at the system : Pmag_em = {} .10^14 W\n".format(self.pow_emission_magnetic / 1e14)
            + "SPI power of the emission at the system : Pspi_em = {} .10^14 W\n".format(self.pow_emission_spi / 1e14)
            + "Kinetic flux of the emission emitted at 1 AU : phi_kin_au = {} .10^10 Jy\n".format(self.flux_kinetic_au / 1e-26 / 1e10)
            + "Magnetic flux of the emission emitted at 1 AU : phi_mag_au = {} .10^10 Jy\n".format(self.flux_magnetic_au / 1e-26 / 1e10)
            + "SPI flux of the emission emitted at 1 AU : phi_spi_au = {} .10^10 Jy\n".format(self.flux_spi_au / 1e-26 / 1e10)
            + "Kinetic flux of the emission received by the instrument : phi_kin = {} mJy\n".format(self._flux_received_kinetic * 1e3 / 1e-26)
            + "Magnetic flux of the emission received by the instrument : phi_mag = {} mJy\n".format(self._flux_received_magnetic * 1e3 / 1e-26)
            + "SPI flux of the emission received by the instrument : phi_spi = {} mJy\n".format(self._flux_received_spi * 1e3 / 1e-26)
        )

    # --------------------------------------------------------- #
    # ------------------------ Methods ------------------------ #

    @property
    def mag_field_planet(self):
        return self._mag_field_planet

    @mag_field_planet.setter
    def mag_field_planet(self, value: dict):
        if "planet" not in value or "magnetic_moment" not in value:
            log.error('KeyError : planet or magnetic_moment not in value')
            raise KeyError("planet or magnetic_moment not in value")
        planet = value["planet"]
        magnetic_moment = value["magnetic_moment"]
        mag_moment_jup = 1.56e27  # A.m-2
        self._mag_field_planet = (
            1e-7
            * 2
            * magnetic_moment.mag_moment
            * mag_moment_jup
            / pow(planet.unnormalize_radius(), 3)
        )

    #=============== Frequencies ===============#

    @property
    def freq_p_planet(self):
        return self._freq_p_planet

    @freq_p_planet.setter
    def freq_p_planet(self, value:dict):
        if "ne" not in value :
            log.error('KeyError : ne not in value')
            raise KeyError("ne not in value")
        me = 9.1093897e-31  # kg
        q = 1.60217733e-19  # C
        epsilon0 = 8.85e-12
        self._freq_p_planet = np.sqrt((q**2) * value["ne"] /( epsilon0 * me))/ (2 * np.pi)

    @property
    def freq_p_star(self):
        return self._freq_p_star

    @freq_p_star.setter
    def freq_p_star(self, value:dict):
        if "ne" not in value :
            log.error('KeyError : ne not in value')
            raise KeyError("ne not in value")
        me = 9.1093897e-31  # kg
        q = 1.60217733e-19  # C
        epsilon0 = 8.85e-12
        self._freq_p_star = np.sqrt((q**2) * value["ne"] /( epsilon0 * me))/ (2 * np.pi)

    @property
    def freq_c_max_planet(self):
        if self._freq_c_max_planet is None:
            me = 9.1093897e-31  # kg
            e = 1.60217733e-19  # C
            self._freq_c_max_planet = e * self.mag_field_planet / (2 * np.pi * me)
        return self._freq_c_max_planet

    @property
    def freq_c_max_star(self):
        return self._freq_c_max_star

    @freq_c_max_star.setter
    def freq_c_max_star(self, value: dict):
        if ("star" not in value)  or ("planet" not in value) or ("stellar_wind" not in value):
            log.error('KeyError : star or planet or stellar_wind not in value')
            raise KeyError("star or planet or stellar_wind not in value")
        me = 9.1093897e-31  # kg
        e = 1.60217733e-19  # C
        self._freq_c_max_star = e * value["star"].magfield / (2 * np.pi * me)

    @property
    def test_escaping_spi(self):
        return self._test_escaping_spi
    @test_escaping_spi.setter
    def test_escaping_spi(self, value:dict):
        dua = 1.49597870700e11  # m
        if (10*self.freq_p_star > self.freq_c_max_star) :
            fc, fp, r, ne_sw = self.find_escaping_freq_spi(value["star"],value["planet"], value["stellar_wind"].distance_alfven_point, value["T_corona"])
            if np.isnan(fc):
                r = value["star"].unnormalize_radius() / dua
                ne_sw = value['stellar_wind'].density_star
                fc = self.freq_c_max_star
                fp = self.freq_p_planet

        else :
            r = value["star"].unnormalize_radius() / dua
            ne_sw = value['stellar_wind'].density_star
            fc = self.freq_c_max_star
            fp = self.freq_p_planet

        self._test_escaping_spi = {"radius" : r, "density" : ne_sw, "fc_star" : fc, "fp_star" : fp}

    @staticmethod
    def find_escaping_freq_spi(star : Star, planet : Planet, d_alfven_point : float, T_corona : float):
        radii = np.logspace(np.log10(0.01),np.log10(planet.stardist),60,endpoint=True)
        me = 9.1093897e-31  # kg
        e = 1.60217733e-19  # C
        epsilon0 = 8.85e-12
        for r in radii :
            try :
                vsw, veff, ne_sw , ne_star = StellarWind._Parker(star=star, distance=r, eccentricity=planet.eccentricity, T=T_corona)
                mag_field = StellarWind._calc_B_total(r,star, vsw, d_alfven_point)
                fp = np.sqrt((e**2) * ne_sw /( epsilon0 * me))/ (2 * np.pi)
                fc = e * mag_field / (2 * np.pi * me)
                if fc > 10*fp :
                    return fc, fp, r, ne_sw
            except ValueError :
                continue
        return np.nan, np.nan, np.nan, np.nan

    #=============== Powers emitted ===============#

    @property
    def pow_emission_kinetic(self):
        return self._pow_emission_kinetic

    @pow_emission_kinetic.setter
    def pow_emission_kinetic(self, value: dict):
        if (
            "planet" not in value
            or "star" not in value
            or "magnetic_moment" not in value
            or "stellar_wind" not in value
        ):
            log.error('KeyError : planet or star or magnetic_moment not in value')
            raise KeyError(
                "planet or star or magnetic_moment or stellar_wind not in value"
            )
        prad_jup = 2.1e11  # W
        standoff_dist_jup = 40.1  # RJ
        density_jup = 1.98e5  # m-3
        veff_jup = 523e3  # m/s

        self._pow_emission_kinetic = (
            prad_jup
            * pow(value["planet"].radius, 2)
            * pow(
                (
                    value["magnetic_moment"].normalize_standoff_dist(
                        planet=value["planet"]
                    )
                    / standoff_dist_jup
                ),
                2,
            )
            * (value["stellar_wind"].density_planet / density_jup)
            * pow(value["stellar_wind"].effective_velocity / veff_jup, 3)
        )

    @property
    def pow_emission_magnetic(self):
        return self._pow_emission_magnetic

    @pow_emission_magnetic.setter
    def pow_emission_magnetic(self, value: dict):
        if (
            "magnetic_moment" not in value
            or "stellar_wind" not in value
        ):
            log.error("KeyError:magnetic_moment or stellar_wind not in value.")
            raise KeyError(
                "magnetic_moment or stellar_wind not in value"
            )
        beta = 2e-3 
        self._pow_emission_magnetic = ( beta * np.pi
            * value["stellar_wind"].effective_velocity 
            * pow(value["stellar_wind"].perp_mag_field, 2)
            * pow(value["magnetic_moment"].magnetosphere_radius,2)
            ) / (4e-7 * np.pi)

    @property
    def pow_emission_spi(self):
        return self._pow_emission_spi

    @pow_emission_spi.setter
    def pow_emission_spi(self, value: dict):
        if (
            "planet" not in value
            or "star" not in value
            or "magnetic_moment" not in value
            or "stellar_wind" not in value
            or "sw_jupiter" not in value
        ):
            log.error("KeyError: planet or star or magnetic_moment or stellar_wind or sw_jupiter not in value.")
            raise KeyError(
                "planet or star or magnetic_moment or stellar_wind or sw_jupiter not in value"
            )
        
        if not np.isnan(self._mag_field_planet) :
            self._pow_emission_spi = self.pow_emission_magnetic
        else :
            R_iono = value["planet"].unnormalize_radius() * 1.2
            beta = 2e-3 
            self._pow_emission_spi = ( beta * np.pi
            * value["stellar_wind"].effective_velocity
            * pow(value["stellar_wind"].perp_mag_field , 2)
            * pow(R_iono,2)
            ) / (4e-7 * np.pi)

    #=============== Flux at 1AU ===============#

    @property
    def flux_kinetic_au(self):
        if self._flux_kinetic_au is None:
            dua = 1.49597870700e11  # m
            try :
                self._flux_kinetic_au = self._pow_emission_kinetic / (
                    1.6 * 0.5 * self.freq_c_max_planet * (dua**2)
                )
            except(ZeroDivisionError):
                self._flux_kinetic_au = np.nan
        return self._flux_kinetic_au

    @property
    def flux_magnetic_au(self):
        if self._flux_magnetic_au is None:
            dua = 1.49597870700e11  # m
            try :
                self._flux_magnetic_au = self._pow_emission_magnetic / (
                    1.6 * 0.5 * self.freq_c_max_planet * (dua**2)
                )
            except(ZeroDivisionError):
                self._flux_magnetic_au = np.nan
        return self._flux_magnetic_au

    @property
    def flux_spi_au(self):
        if self._flux_spi_au is None:
            dua = 1.49597870700e11  # m
            try :
                self._flux_spi_au = self._pow_emission_spi / (
                    0.16 * 0.5 * self.freq_c_max_star * (dua**2)
                )
            except(ZeroDivisionError):
                self._flux_spi_au = np.nan
        return self._flux_spi_au

    #=============== Flux received at Earth ===============#

    @property
    def flux_received_kinetic(self):
        return self._flux_received_kinetic

    @flux_received_kinetic.setter
    def flux_received_kinetic(self, value: dict):
        if "star" not in value:
            log.error("KeyError: star not in value.")
            raise KeyError("star not in value")

        pc = 3.08568e16  # m
        try : 
            self._flux_received_kinetic = self._pow_emission_kinetic / (
                1.6 * 0.5 * self.freq_c_max_planet * pow(value["star"].obs_dist * pc, 2)
            )
        except (ZeroDivisionError):
            self._flux_received_kinetic = np.nan

    @property
    def flux_received_magnetic(self):
        return self._flux_received_magnetic

    @flux_received_magnetic.setter
    def flux_received_magnetic(self, value: dict):
        if "star" not in value:
            log.error("KeyError: star not in value.")
            raise KeyError("star not in value")

        pc = 3.08568e16  # m
        try :
            self._flux_received_magnetic = self._pow_emission_magnetic / (
                1.6 * 0.5 * self.freq_c_max_planet * pow(value["star"].obs_dist * pc, 2)
            )
        except (ZeroDivisionError):
            self._flux_received_magnetic = np.nan

    @property
    def flux_received_spi(self):
        return self._flux_received_spi

    @flux_received_spi.setter
    def flux_received_spi(self, value: dict):
        if ("star" not in value) or "stellar_wind" not in value:
            log.error("KeyError: star or stellar_wind not in value.")
            raise KeyError("star or stellar_wind not in value")

        pc = 3.08568e16  # m
        if value["stellar_wind"].alfven_velocity < value["stellar_wind"].velocity_sw :
            self._flux_received_spi = np.nan
        else :
            try :
                self._flux_received_spi = self._pow_emission_spi / (
                    0.16 * 0.5 * self.freq_c_max_star * pow(value["star"].obs_dist * pc, 2)
                )
            except (ZeroDivisionError):
                self._flux_received_spi = np.nan
    
    #=============== Flux received at Earth ===============#

    @property
    def tau_free_free_spi(self):
        return self._tau_free_free_spi
    
    @tau_free_free_spi.setter
    def tau_free_free_spi(self, value : dict):
        if ("star" not in value) or "stellar_wind" not in value:
            log.error("KeyError: star or stellar_wind not in value.")
            raise KeyError("star or stellar_wind not in value")
        star = value["star"]
        stellar_wind = value["stellar_wind"]
        dua = 1.49597870700e11  # m

        self._tau_free_free_spi = 111 * pow(stellar_wind.corona_temperature, -0.5) * (self.test_escaping_spi["density"]**2) * pow(self.test_escaping_spi['radius'] * dua,2)/ ((self.test_escaping_spi['fc_star']**2) * star.unnormalize_mass())

    @property
    def tau_free_free_ms(self):
        return self._tau_free_free_ms
    
    @tau_free_free_ms.setter
    def tau_free_free_ms(self, value:dict):
        dua = 1.49597870700e11  # m
        if ("planet" not in value) or "stellar_wind" not in value:
            log.error("KeyError: planet or stellar_wind not in value.")
            raise KeyError("planet or stellar_wind not in value")
        planet = value["planet"]
        stellar_wind = value["stellar_wind"]
        self._tau_free_free_ms = 1.8e-12 * pow(stellar_wind.corona_temperature, -3.5) * (stellar_wind.density_planet**2) * (planet.stardist *dua)/ (self.freq_c_max_planet**2)


